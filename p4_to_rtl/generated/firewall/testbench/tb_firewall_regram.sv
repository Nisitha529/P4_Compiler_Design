  logic [15:0]      dep_pkt_len;
  logic             dep_valid_out;

  deparser_generated dep_dut (
    .clk              (clk),              .rst_n           (rst_n),
    .valid_in         (dep_valid_in),
    .ethernet_valid   (dep_eth_valid),    .ipv4_valid      (dep_ipv4_valid),
