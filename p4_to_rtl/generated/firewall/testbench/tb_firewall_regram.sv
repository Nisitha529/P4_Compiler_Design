// ============================================================================
// tb_firewall_regram.sv -- latency-parameterized clone of tb_firewall.sv, used
// to prove that `--register-ram` (synchronous register reads, so bloom filters
// infer as real Block RAM) is FUNCTIONALLY equivalent to the default
// asynchronous-read emission -- only deeper.
//
// tb_firewall.sv is deliberately cycle-exact, so it cannot be reused directly:
// every result is sampled at a hardcoded pipeline depth. This file is that TB
// with exactly two mechanical changes, both gated on `PIPE_EXTRA:
//   * the 20 four-edge result-drain sites become `repeat(4 + `PIPE_EXTRA)`
//   * INT5 (the one test that intentionally asserts pipeline DEPTH) gets
//     `PIPE_EXTRA extra "still not valid yet" edges before its valid_out=1
//     check, so it measures the new depth instead of failing on it.
// The parser section is untouched -- the parser FSM is not affected by
// register emission and its cycle counts must stay exact.
//
// Run BOTH ways; both must be green, and that pairing is the actual claim:
//
//   # default RTL, unchanged depth (5)
//   iverilog -g2012 -o sim_base tb_firewall_regram.sv \
//     ../processing_generated.sv ../parser_generated.sv \
//     ../deparser_generated.sv ../ipv4_lpm_table.sv ../check_ports_table.sv
//   vvp sim_base            # -> 79 passed, 0 failed
//
//   # --register-ram RTL, depth 7 (one extra stage per bloom-filter read)
//   iverilog -g2012 -DPIPE_EXTRA=2 -o sim_ram tb_firewall_regram.sv \
//     <register-ram processing_generated.sv> ../parser_generated.sv \
//     ../deparser_generated.sv ../ipv4_lpm_table.sv ../check_ports_table.sv
//   vvp sim_ram             # -> 81 passed, 0 failed
//
// PIPE_EXTRA is 2 (not 1) because each register .read() currently gets its own
// pipeline boundary; firewall.p4 reads bloom_filter_1 and bloom_filter_2 back
// to back, so it pays two. Sharing one boundary across reads whose addresses
// are all ready before the first read is a known available optimization.
// ============================================================================
// tb_firewall.sv — Comprehensive self-checking testbench for firewall.p4
//
// Pipeline: V1Switch → MyIngress (processing_generated)
//
// P4 firewall semantics under test:
//   IPv4 LPM table  (ipv4_forward / drop / NoAction, default=drop on miss)
//   check_ports table (set_direction: 0=internal, 1=external)
//   Bloom filter (direction=0 SYN → write; direction=1 → read+allow/drop)
//   Three-level parser: Ethernet → IPv4 → TCP
//
// Hash function (XOR stub generated by compiler):
//   pos = (ipAddr1 ^ ipAddr2 ^ port1 ^ port2 ^ protocol) & 12'hFFF
//   XOR is commutative, so direction-0 and direction-1 hashes are equal.
//
// Test IPs / ports:
//   Internal host: 192.168.0.1  (0xC0A80001), ingress_port=1
//   External host:  10.0.0.1   (0x0A000001), ingress_port=2
//   Client port: 0x1234   HTTP port: 0x0050 (80)
//   Unsolicited src: 1.2.3.4  (0x01020304)
//
//   SYN/reply hash  = (0xC0A80001^0x0A000001^0x1234^0x0050^6)&0xFFF = 0x262 (610)
//   Unsolicited hash= (0xC0A80001^0x01020304^0x1234^0x0050^6)&0xFFF = 0x167 (359)
//
// Compile (from this directory):
//   iverilog -g2012 -o sim tb_firewall.sv \
//     ../parser_generated.sv ../processing_generated.sv \
//     ../deparser_generated.sv \
//     ../ipv4_lpm_table.sv ../check_ports_table.sv
//   vvp sim
// ============================================================================
