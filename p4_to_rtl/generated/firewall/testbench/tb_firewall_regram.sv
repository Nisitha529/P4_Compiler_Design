    .pkt_hdr_out      (dep_pkt_out),
    .pkt_hdr_len      (dep_pkt_len),
    .valid_out        (dep_valid_out)
  );

  // Pre-computed bloom filter hash positions (12-bit XOR stub, 4096-entry BF)
  // hash = (ipAddr1 ^ ipAddr2 ^ port1 ^ port2 ^ proto) & 12'hFFF
  localparam [11:0] HASH_192_10_1234_50_6 =
      (32'hC0A80001 ^ 32'h0A000001 ^ 32'h1234 ^ 32'h0050 ^ 32'h6) & 12'hFFF;
  // = 0x262
  localparam [11:0] HASH_192_1234_5678_01BB_6 =
      (32'hC0A80001 ^ 32'h0A000001 ^ 32'h5678 ^ 32'h01BB ^ 32'h6) & 12'hFFF;
  // = 0x7C5

  // ==========================================================================
  // Test infrastructure
  // ==========================================================================
  int pass_cnt = 0, fail_cnt = 0;

  task automatic chk(input string name, input logic cond);
    if (cond) begin $display("    [PASS] %s", name); pass_cnt++; end
    else      begin $display("    [FAIL] %s", name); fail_cnt++; end
  endtask

  task do_reset;
    rst_n = 0; p_valid_in = 0; pr_valid_in = 0;
    pr_eth_valid = 0; pr_ipv4_valid = 0; pr_tcp_valid = 0;
    dep_eth_valid = 0; dep_ipv4_valid = 0; dep_tcp_valid = 0;
    repeat(5) @(posedge clk); @(negedge clk);
    rst_n = 1; @(posedge clk); #1;
  endtask

  // Write one ipv4_lpm entry
  task lpm_write(input [9:0] idx, input [31:0] key, input [5:0] pfx,
                 input [1:0] act,  input [47:0] dstM, input [8:0] portn);
    @(negedge clk);
    lpm_cp_idx=idx; lpm_cp_key=key; lpm_cp_pfx=pfx;
    lpm_cp_act=act; lpm_cp_dstM=dstM; lpm_cp_port=portn;
    lpm_cp_en=1;
    @(posedge clk); #1;
    lpm_cp_en=0;
  endtask

  // Write one check_ports entry (action=set_direction)
  task chkp_write(input [9:0] idx, input [8:0] ing, input [8:0] egr, input [0:0] dir);
    @(negedge clk);
    cp_cp_idx=idx; cp_cp_ing=ing; cp_cp_egr=egr;
    cp_cp_act=1'b1; cp_cp_dir=dir;
    cp_cp_en=1;
    @(posedge clk);
    #1;
    cp_cp_en=0;
  endtask

  // One-cycle valid strobe so bloom filter writes commit
  task send_packet;
    // Data path is now 4 cycles deep (ipv4_lpm: lookup + output register,
    // then check_ports: lookup + output register) before
    // bloom_filter_*_wr_en is computed, plus 1 more cycle for that write
    // to actually commit to bloom_filter_*_mem -- 5 edges total.
    pr_valid_in=1; @(posedge clk); #1; pr_valid_in=0;
    @(posedge clk); #1;
    @(posedge clk); #1;
    @(posedge clk); #1;
    @(posedge clk); #1;  // let register write propagate
    repeat(`PIPE_EXTRA) @(posedge clk); #1;
  endtask

  // ==========================================================================
  // MAIN TEST
  // ==========================================================================
  initial begin
    // $dumpfile("tb_firewall.vcd");  // disabled for performance
    // $dumpvars(1, tb_firewall);

    // ──────────────────────────────────────────────────────────────────────
    // SECTION 1 — PARSER FSM (three-level chain)
    // ──────────────────────────────────────────────────────────────────────
    $display("\n══ Section 1: Parser FSM (three-level) ════════════════════════");

    // P1: IPv4+TCP → 4 clock cycles to ACCEPT
    $display("  P1: 0x0800 / proto=6 → start→eth→ipv4→tcp→accept");
    do_reset();
    p_eth_type=16'h0800; p_ipv4_proto=8'd6; p_valid_in=1; #1;
    chk("P1 START: !eth",     !p_ext_eth);
    @(posedge clk); #1;
    chk("P1 ETH: ext_eth",    p_ext_eth);
    @(posedge clk); #1;
    chk("P1 IPV4: ext_ipv4",  p_ext_ipv4);
    @(posedge clk); #1;
    chk("P1 TCP: ext_tcp",    p_ext_tcp);
    @(posedge clk); #1;
    chk("P1 ACCEPT: done",    p_done);
    p_valid_in=0;

    // P2: IPv4+UDP → accept after parse_ipv4 (no TCP state)
    $display("  P2: 0x0800 / proto=17 → eth→ipv4→accept (no tcp)");
    do_reset();
    p_eth_type=16'h0800; p_ipv4_proto=8'd17; p_valid_in=1;
    @(posedge clk); #1; @(posedge clk); #1; @(posedge clk); #1;
    chk("P2 done",       p_done);
    chk("P2 !tcp",       !p_ext_tcp);
    p_valid_in=0;

    // P3: Non-IPv4 (ARP) → accept after parse_ethernet
    $display("  P3: 0x0806 (ARP) → eth→accept");
    do_reset();
    p_eth_type=16'h0806; p_valid_in=1;
    @(posedge clk); #1; @(posedge clk); #1;
    chk("P3 done",       p_done);
    chk("P3 !ipv4",      !p_ext_ipv4);
    chk("P3 !tcp",       !p_ext_tcp);
    p_valid_in=0;

    // P4: ICMP (proto=1) → eth→ipv4→accept (3 clocks: ETH→IPV4→ACCEPT)
    $display("  P4: 0x0800 / proto=1 (ICMP) → eth→ipv4→accept");
    do_reset();
    p_eth_type=16'h0800; p_ipv4_proto=8'd1; p_valid_in=1;
    @(posedge clk); #1;               // state=PARSE_ETHERNET
    @(posedge clk); #1;               // state=PARSE_IPV4 → ext_ipv4=1
    chk("P4 ipv4",       p_ext_ipv4); // check HERE while in IPV4 state
    @(posedge clk); #1;               // state=ACCEPT → done=1
    chk("P4 done",       p_done);
    chk("P4 !tcp",       !p_ext_tcp);
    p_valid_in=0;

    // ──────────────────────────────────────────────────────────────────────
    // SECTION 2 — ipv4_lpm TABLE (default action = drop on miss)
    // ──────────────────────────────────────────────────────────────────────
    $display("\n══ Section 2: ipv4_lpm Table ══════════════════════════════════");

    // Program table:
    //   entry 0: 10.0.0.0/24 → ipv4_forward, MAC=AA:BB:CC:DD:EE:FF, port=3
    //   entry 1: 192.168.0.0/24 → ipv4_forward, MAC=11:22:33:44:55:66, port=1
    do_reset();
    lpm_write(0, 32'h0A000000, 6'd24, 2'd1, 48'hAABBCCDDEEFF, 9'd3);
    lpm_write(1, 32'hC0A80000, 6'd24, 2'd1, 48'h112233445566, 9'd1);

    // L1: IPv4 with no matching entry → drop (default)
    $display("  L1: LPM miss (1.1.1.1) → drop by default action");
    pr_eth_valid=1; pr_ipv4_valid=1; pr_tcp_valid=0;
    pr_ipv4_src=32'hC0A80001; pr_ipv4_dst=32'h01010101;
    pr_ipv4_proto=8'd6; pr_ipv4_ttl=64;
    pr_ingress_port=9'd1; pr_egress_spec_i=9'd0; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("L1: drop=1",           pr_drop);
    chk("L1: egress_spec=0",    pr_o_egress_spec==9'd0);

    // L2: Hit entry 0 → ipv4_forward
    $display("  L2: LPM hit (10.0.0.1) → MAC rewrite, TTL--, port=3");
    pr_ipv4_dst=32'h0A000001; pr_ipv4_ttl=64;
    pr_eth_dst=48'h112233445566; pr_eth_src=48'hCAFECAFECAFE;
    pr_egress_spec_i=9'd3; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("L2: not dropped",          !pr_drop);
    chk("L2: eth_dst=AA:BB...",     pr_o_eth_dst==48'hAABBCCDDEEFF);
    chk("L2: eth_src=old_eth_dst",  pr_o_eth_src==48'h112233445566);
    chk("L2: TTL decremented",      pr_o_ipv4_ttl==8'd63);
    chk("L2: egress_spec=3",        pr_o_egress_spec==9'd3);

    // L3: Hit entry 1 → forward to port=1
    $display("  L3: LPM hit (192.168.0.2) → port=1");
    pr_ipv4_dst=32'hC0A80002; pr_ipv4_ttl=128; pr_egress_spec_i=9'd1; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("L3: not dropped",      !pr_drop);
    chk("L3: eth_dst=11:22...", pr_o_eth_dst==48'h112233445566);
    chk("L3: egress_spec=1",    pr_o_egress_spec==9'd1);
    chk("L3: TTL=127",          pr_o_ipv4_ttl==8'd127);

    // L4: Non-IPv4 → pass through (no LPM applied)
    $display("  L4: Non-IPv4 → pass-through, not dropped");
    pr_eth_valid=1; pr_ipv4_valid=0; pr_tcp_valid=0;
    pr_eth_dst=48'hDEADBEEFCAFE; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("L4: not dropped",           !pr_drop);
    chk("L4: eth_dst pass-through",  pr_o_eth_dst==48'hDEADBEEFCAFE);

    // L5: TTL=1 → should become TTL=0 after decrement (edge)
    $display("  L5: TTL=1 → decrements to 0 (edge case)");
    pr_eth_valid=1; pr_ipv4_valid=1;
    pr_ipv4_dst=32'h0A000001; pr_ipv4_ttl=8'd1;
    pr_eth_dst=48'hAABBCCDDEEFF; pr_egress_spec_i=9'd3; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("L5: TTL=0",   pr_o_ipv4_ttl==8'd0);
    chk("L5: not drop",!pr_drop);

    // ──────────────────────────────────────────────────────────────────────
    // SECTION 3 — check_ports + direction
    // ──────────────────────────────────────────────────────────────────────
    $display("\n══ Section 3: check_ports Table + set_direction ═══════════════");

    do_reset();
    lpm_write(0, 32'h0A000000, 6'd24, 2'd1, 48'hAABBCCDDEEFF, 9'd3);
    lpm_write(1, 32'hC0A80000, 6'd24, 2'd1, 48'h112233445566, 9'd1);
    chkp_write(0, 9'd1, 9'd3, 1'b0);   // ingress=1, egress=3 → internal
    chkp_write(1, 9'd2, 9'd1, 1'b1);   // ingress=2, egress=1 → external

    // C1: check_ports miss → direction stays 0, no bloom interaction
    $display("  C1: TCP, check_ports miss (ingress=5) → not drop-by-firewall");
    pr_eth_valid=1; pr_ipv4_valid=1; pr_tcp_valid=1;
    pr_ipv4_src=32'hC0A80001; pr_ipv4_dst=32'h0A000001;
    pr_ipv4_proto=8'd6; pr_ipv4_ttl=64;
    pr_tcp_srcPort=16'h1234; pr_tcp_dstPort=16'h0050;
    pr_tcp_syn=0; pr_tcp_ack=1;
    pr_ingress_port=9'd5;   // not in check_ports → miss
    pr_egress_spec_i=9'd3; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("C1: not dropped (check_ports miss)", !pr_drop);

    // C2: TCP, direction=0, no SYN → bloom filter not written
    $display("  C2: TCP from internal, no SYN → not dropped, no bloom write");
    pr_ingress_port=9'd1; pr_egress_spec_i=9'd3;
    pr_tcp_syn=0; pr_tcp_ack=0; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("C2: not dropped", !pr_drop);

    // C3: direction=1, bloom NOT set → drop
    $display("  C3: TCP from external, bloom NOT set → dropped");
    pr_ipv4_src=32'h0A000001; pr_ipv4_dst=32'hC0A80001;
    pr_tcp_srcPort=16'h0050; pr_tcp_dstPort=16'h1234;
    pr_tcp_ack=1; pr_tcp_syn=0;
    pr_ingress_port=9'd2; pr_egress_spec_i=9'd1; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("C3: drop=1 (bloom not set)", pr_drop);

    // ──────────────────────────────────────────────────────────────────────
    // SECTION 4 — Bloom filter write (direction=0, SYN)
    // ──────────────────────────────────────────────────────────────────────
    $display("\n══ Section 4: Bloom Filter Write (SYN from internal) ══════════");

    do_reset();
    lpm_write(0, 32'h0A000000, 6'd24, 2'd1, 48'hAABBCCDDEEFF, 9'd3);
    lpm_write(1, 32'hC0A80000, 6'd24, 2'd1, 48'h112233445566, 9'd1);
    chkp_write(0, 9'd1, 9'd3, 1'b0);
    chkp_write(1, 9'd2, 9'd1, 1'b1);

    // FW1: SYN from internal → bloom filter written
    $display("  FW1: SYN (direction=0) → bloom filter written at index 0x262");
    pr_eth_valid=1; pr_ipv4_valid=1; pr_tcp_valid=1;
    pr_ipv4_src=32'hC0A80001; pr_ipv4_dst=32'h0A000001;
    pr_ipv4_proto=8'd6; pr_ipv4_ttl=64;
    pr_tcp_srcPort=16'h1234; pr_tcp_dstPort=16'h0050;
    pr_tcp_syn=1; pr_tcp_ack=0;
    pr_ingress_port=9'd1; pr_egress_spec_i=9'd3;
    send_packet();
    chk("FW1: SYN forwarded (not dropped)", !pr_drop);
    chk("FW1: egress_spec=3",              pr_o_egress_spec==9'd3);
    // hash(192.168.0.1, 10.0.0.1, 0x1234, 0x0050, 6) & 0x7 = 0x2
    chk("FW1: bf1_mem[2]=1", proc_dut.bloom_filter_1_mem[HASH_192_10_1234_50_6]===1'b1);
    chk("FW1: bf2_mem[2]=1", proc_dut.bloom_filter_2_mem[HASH_192_10_1234_50_6]===1'b1);
    // Verify unsolicited index is still 0
    chk("FW1: bf1_mem[7]=0", proc_dut.bloom_filter_1_mem[3'h7]===1'b0);

    // FW2: SYN with ipv4_valid=0 → no bloom write (guard fails at ipv4_valid)
    $display("  FW2: invalid IPv4 → bloom filter NOT written");
    pr_ipv4_valid=0;
    send_packet();
    // bloom at the above index should remain from FW1, nothing else written
    chk("FW2: bloom unchanged", proc_dut.bloom_filter_1_mem[HASH_192_10_1234_50_6]===1'b1);
    pr_ipv4_valid=1;

    // ──────────────────────────────────────────────────────────────────────
    // SECTION 5 — Bloom filter read: established → ALLOW
    // ──────────────────────────────────────────────────────────────────────
    $display("\n══ Section 5: Bloom Filter Read — Established Flow → ALLOW ════");

    // FW3: External ACK on established connection
    $display("  FW3: External ACK (established, bloom set) → allowed");
    pr_ipv4_src=32'h0A000001; pr_ipv4_dst=32'hC0A80001;
    pr_tcp_srcPort=16'h0050; pr_tcp_dstPort=16'h1234;
    pr_tcp_syn=0; pr_tcp_ack=1;
    pr_ingress_port=9'd2; pr_egress_spec_i=9'd1; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("FW3: allowed (bloom set at 0x262)", !pr_drop);
    chk("FW3: forwarded to port=1",          pr_o_egress_spec==9'd1);

    // FW4: External FIN on established connection
    $display("  FW4: External FIN (established) → allowed");
    pr_tcp_ack=0; pr_tcp_fin=1; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("FW4: FIN allowed", !pr_drop);
    pr_tcp_fin=0;

    // FW5: Another request on same 5-tuple
    $display("  FW5: Same 5-tuple, different flags → allowed");
    pr_tcp_ack=1; pr_tcp_rst=0; pr_tcp_syn=0; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("FW5: subsequent packet allowed", !pr_drop);

    // ──────────────────────────────────────────────────────────────────────
    // SECTION 6 — Bloom filter read: unestablished → DROP
    // ──────────────────────────────────────────────────────────────────────
    $display("\n══ Section 6: Bloom Filter Read — Unestablished → DROP ════════");

    // FW6: Different source IP (unsolicited)
    $display("  FW6: Unsolicited external (diff src IP, index=0x167) → drop");
    pr_ipv4_src=32'h01020304;  // 1.2.3.4 — never SYN'd
    pr_ipv4_dst=32'hC0A80001;
    pr_tcp_srcPort=16'h0050; pr_tcp_dstPort=16'h1234;
    pr_tcp_ack=1; pr_tcp_syn=0;
    pr_ingress_port=9'd2; pr_egress_spec_i=9'd1; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    // hash(C0A80001^01020304^1234^0050^6) & 0x7 = 0x7 (not written)
    chk("FW6: unsolicited dropped",  pr_drop);
    chk("FW6: bf1[7]=0 (never written)",
        proc_dut.bloom_filter_1_mem[3'h7]===1'b0);

    // FW7: Unsolicited SYN from external — no existing connection
    $display("  FW7: Unsolicited SYN from external → dropped");
    pr_tcp_syn=1; pr_tcp_ack=0; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("FW7: unsolicited SYN dropped", pr_drop);
    pr_tcp_syn=0;

    // FW8: Different destination port → different hash, not established
    $display("  FW8: Different dst port → unestablished, dropped");
    pr_ipv4_src=32'h0A000001; pr_ipv4_dst=32'hC0A80001;
    pr_tcp_srcPort=16'h0050; pr_tcp_dstPort=16'hABCD;  // different client port
    pr_tcp_ack=1; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("FW8: different-port dropped", pr_drop);

    // ──────────────────────────────────────────────────────────────────────
    // SECTION 7 — Non-TCP IPv4 (UDP/ICMP: routing only)
    // ──────────────────────────────────────────────────────────────────────
    $display("\n══ Section 7: Non-TCP IPv4 — Routing Only (no bloom check) ════");

    do_reset();
    lpm_write(0, 32'h0A000000, 6'd24, 2'd1, 48'hAABBCCDDEEFF, 9'd3);

    $display("  U1: UDP to 10.0.0.1 → forwarded");
    pr_eth_valid=1; pr_ipv4_valid=1; pr_tcp_valid=0;
    pr_ipv4_src=32'hC0A80001; pr_ipv4_dst=32'h0A000001;
    pr_ipv4_proto=8'd17; pr_ipv4_ttl=64;
    pr_ingress_port=9'd1; pr_egress_spec_i=9'd3; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("U1: UDP not dropped",   !pr_drop);
    chk("U1: MAC rewritten",     pr_o_eth_dst==48'hAABBCCDDEEFF);
    chk("U1: TTL decremented",   pr_o_ipv4_ttl==8'd63);
    chk("U1: egress_spec=3",     pr_o_egress_spec==9'd3);

    $display("  U2: ICMP to 10.0.0.1 → forwarded");
    pr_ipv4_proto=8'd1; pr_ipv4_ttl=64; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("U2: ICMP not dropped",  !pr_drop);
    chk("U2: MAC rewritten",     pr_o_eth_dst==48'hAABBCCDDEEFF);

    $display("  U3: UDP to unrouted address → dropped (LPM miss)");
    pr_ipv4_dst=32'hFFFFFFFF; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("U3: unrouted UDP dropped", pr_drop);

    // ──────────────────────────────────────────────────────────────────────
    // SECTION 8 — DEPARSER: Ethernet + IPv4 + TCP packing
    //   Layout: [431:320]=Ethernet(112b)  [319:160]=IPv4(160b)  [159:0]=TCP(160b)
    //   TCP SYN bit is at offset 16+16+32+32+4+4+1+1+1+1+1+1 = 110 from TCP MSB
    //   → bit position = 159 - 110 = 49 within TCP block → bus bit [49]
    // ──────────────────────────────────────────────────────────────────────
    $display("\n══ Section 8: Deparser Packing ════════════════════════════════");

    dep_eth_dst=48'hAABBCCDDEEFF; dep_eth_src=48'h112233445566;
    dep_eth_type=16'h0800;
    dep_ipv4_ver=4; dep_ipv4_ihl=5; dep_ipv4_ds=8'd46;
    dep_ipv4_len=16'd60; dep_ipv4_id=16'h1234;
    dep_ipv4_flg=3'b010; dep_ipv4_off=13'd0;
    dep_ipv4_ttl=8'd63; dep_ipv4_proto=8'd6;
    dep_ipv4_chk=16'hBEEF;
    dep_ipv4_src=32'hC0A80001; dep_ipv4_dst=32'h0A000001;
    dep_tcp_src=16'h1234; dep_tcp_dst=16'h0050;
    dep_tcp_seq=32'hDEADBEEF; dep_tcp_ack=32'hCAFEBABE;
    dep_tcp_doff=4'd5; dep_tcp_res=0;
    dep_tcp_cwr=0; dep_tcp_ece=0; dep_tcp_urg=0; dep_tcp_ackf=0;
    dep_tcp_psh=0; dep_tcp_rst=0; dep_tcp_syn=1; dep_tcp_fin=0;
    dep_tcp_win=16'h7FFF; dep_tcp_chk=16'h5678; dep_tcp_urgp=0;

    // D1: All three headers valid
    $display("  D1: eth+ipv4+tcp valid → pkt_hdr_len=432");
    dep_eth_valid=1; dep_ipv4_valid=1; dep_tcp_valid=1; #1;
    chk("D1: len=432",            dep_pkt_len==16'd432);
    chk("D1: eth dst [431:384]",  dep_pkt_out[431:384]==48'hAABBCCDDEEFF);
    chk("D1: eth src [383:336]",  dep_pkt_out[383:336]==48'h112233445566);
    chk("D1: eth type [335:320]", dep_pkt_out[335:320]==16'h0800);
    chk("D1: ipv4 src [223:192]", dep_pkt_out[223:192]==32'hC0A80001);
    chk("D1: ipv4 dst [191:160]", dep_pkt_out[191:160]==32'h0A000001);
    // TCP srcPort is at MSB of TCP block = bits [159:144]
    chk("D1: tcp srcPort [159:144]", dep_pkt_out[159:144]==16'h1234);
    // TCP SYN bit: 110 bits from TCP MSB → bit 159-110=49 within TCP → bus bit [49]
    chk("D1: tcp SYN bit [49]",   dep_pkt_out[49]==1'b1);

    // D2: No TCP → len=272
    $display("  D2: eth+ipv4 only → pkt_hdr_len=272");
    dep_tcp_valid=0; #1;
    chk("D2: len=272",         dep_pkt_len==16'd272);
    chk("D2: tcp slot=0",      dep_pkt_out[159:0]=={160{1'b0}});

    // D3: Ethernet only → len=112
    $display("  D3: eth only → pkt_hdr_len=112");
    dep_ipv4_valid=0; #1;
    chk("D3: len=112",         dep_pkt_len==16'd112);
    chk("D3: ipv4+tcp=0",      dep_pkt_out[319:0]=={320{1'b0}});

    // D4: No headers → 0
    $display("  D4: no headers → pkt_hdr_len=0");
    dep_eth_valid=0; #1;
    chk("D4: len=0",   dep_pkt_len==16'd0);
    chk("D4: all 0",   dep_pkt_out=={DEP_W{1'b0}});

    // ──────────────────────────────────────────────────────────────────────
    // SECTION 9 — Integration: full connection lifecycle
    // ──────────────────────────────────────────────────────────────────────
    $display("\n══ Section 9: Integration — Full Connection Lifecycle ══════════");

    do_reset();
    lpm_write(0, 32'h0A000000, 6'd24, 2'd1, 48'hAABBCCDDEEFF, 9'd3);
    lpm_write(1, 32'hC0A80000, 6'd24, 2'd1, 48'h112233445566, 9'd1);
    chkp_write(0, 9'd1, 9'd3, 1'b0);
    chkp_write(1, 9'd2, 9'd1, 1'b1);

    // Step 1: Internal client sends SYN to HTTPS server
    $display("  INT1: SYN from 192.168.0.1:22136 → 10.0.0.1:443 (opens connection)");
    pr_eth_valid=1; pr_ipv4_valid=1; pr_tcp_valid=1;
    pr_ipv4_src=32'hC0A80001; pr_ipv4_dst=32'h0A000001;
    pr_ipv4_proto=8'd6; pr_ipv4_ttl=64;
    pr_tcp_srcPort=16'h5678; pr_tcp_dstPort=16'h01BB; // port 443
    pr_tcp_syn=1; pr_tcp_ack=0;
    pr_ingress_port=9'd1; pr_egress_spec_i=9'd3;
    send_packet();
    chk("INT1: SYN forwarded",    !pr_drop);
    chk("INT1: bloom written",
        proc_dut.bloom_filter_1_mem[HASH_192_1234_5678_01BB_6]===1'b1);

    // Step 2: Server SYN-ACK → allowed
    $display("  INT2: SYN-ACK from 10.0.0.1:443 → 192.168.0.1:22136 → allowed");
    pr_ipv4_src=32'h0A000001; pr_ipv4_dst=32'hC0A80001;
    pr_tcp_srcPort=16'h01BB; pr_tcp_dstPort=16'h5678;
    pr_tcp_syn=1; pr_tcp_ack=1;
    pr_ingress_port=9'd2; pr_egress_spec_i=9'd1; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("INT2: SYN-ACK allowed",    !pr_drop);
    chk("INT2: forwarded to port=1", pr_o_egress_spec==9'd1);

    // Step 3: More data from server
    $display("  INT3: Server data → allowed");
    pr_tcp_syn=0; pr_tcp_ack=1; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("INT3: data allowed", !pr_drop);

    // Step 4: A different attacker tries to reach the same client
    $display("  INT4: Attacker 2.3.4.5 → internal, no SYN → dropped");
    pr_ipv4_src=32'h02030405;
    pr_tcp_srcPort=16'h01BB; pr_tcp_dstPort=16'h5678;
    pr_tcp_syn=0; pr_tcp_ack=1;
    pr_ingress_port=9'd2; pr_egress_spec_i=9'd1; repeat(4 + `PIPE_EXTRA) @(posedge clk); #1;
    chk("INT4: attacker dropped", pr_drop);

    // Step 5: valid_out pipeline register
    // ipv4_lpm and check_ports are each now a 2-cycle boundary (lookup +
    // output register -- see emit_table.py/emit_processing.py), so
    // valid_out is 5 cycles behind valid_in (1 baseline + 4 boundary).
    $display("  INT5: valid_out is five-cycle delayed (1 baseline + 4 boundary)");
    do_reset();
    pr_valid_in=1; #1;
    chk("INT5: valid_out=0 before edge", !pr_valid_out);
    @(posedge clk); #1;
    chk("INT5: valid_out=0 after 1st edge", !pr_valid_out);
    pr_valid_in=0;
    @(posedge clk); #1;
    chk("INT5: valid_out=0 after 2nd edge", !pr_valid_out);
    @(posedge clk); #1;
    chk("INT5: valid_out=0 after 3rd edge", !pr_valid_out);
    @(posedge clk); #1;
    chk("INT5: valid_out=0 after 4th edge", !pr_valid_out);
    if (`PIPE_EXTRA > 0) begin
      repeat(`PIPE_EXTRA) begin @(posedge clk); #1;
        chk("INT5: valid_out=0 during extra reg-RAM stage", !pr_valid_out); end
    end
    @(posedge clk); #1;
    chk("INT5: valid_out=1 after 5th edge",   pr_valid_out);
    @(posedge clk); #1;
    chk("INT5: valid_out=0 deasserted",  !pr_valid_out);

    // ──────────────────────────────────────────────────────────────────────
    $display("\n════════════════════════════════════════════════════════════════");
    $display("  Results: %0d passed, %0d failed  (total %0d)",
             pass_cnt, fail_cnt, pass_cnt+fail_cnt);
    $display("════════════════════════════════════════════════════════════════");
    if (fail_cnt == 0)
      $display("  ALL TESTS PASSED");
    else
      $display("  FAILURES DETECTED — see [FAIL] lines above");
    $finish;
  end

